def font(size, bold=False):
    candidates = [
        "C:/Windows/Fonts/timesbd.ttf" if bold else "C:/Windows/Fonts/times.ttf",
        "C:/Windows/Fonts/arialbd.ttf" if bold else "C:/Windows/Fonts/arial.ttf",
    ]
    for candidate in candidates:
        if Path(candidate).exists():
            return ImageFont.truetype(candidate, size)
    return ImageFont.load_default()


def wrap(draw, text, font_obj, width):
    lines = []
    for paragraph in str(text).split("\n"):
        words = paragraph.split()
        if not words:
            lines.append("")
            continue
        current = words[0]
        for word in words[1:]:
            trial = f"{current} {word}"
            if draw.textbbox((0, 0), trial, font=font_obj)[2] <= width:
                current = trial
            else:
                lines.append(current)
                current = word
        lines.append(current)
    return lines


def draw_table(headers, rows, widths, output_path):
    margin = 18
    padding = 12
    header_font = font(23, bold=True)
    body_font = font(20)
    line_gap = 5
    probe = Image.new("RGB", (10, 10), "white")
    draw = ImageDraw.Draw(probe)
    rendered = []
    for row_index, row in enumerate([headers] + rows):
        current_font = header_font if row_index == 0 else body_font
        cells = [wrap(draw, cell, current_font, widths[i] - 2 * padding) for i, cell in enumerate(row)]
        line_height = draw.textbbox((0, 0), "Ag", font=current_font)[3] + line_gap
        height = max(len(lines) * line_height for lines in cells) + 2 * padding
        rendered.append((cells, current_font, line_height, max(height, 62 if row_index == 0 else 76)))
    img = Image.new("RGB", (sum(widths) + 2 * margin, sum(r[3] for r in rendered) + 2 * margin), "white")
    draw = ImageDraw.Draw(img)
    y = margin
    for row_index, (cells, current_font, line_height, height) in enumerate(rendered):
        x = margin
        fill = "#D9EAF7" if row_index == 0 else "#FFFFFF"
        draw.rectangle([margin, y, margin + sum(widths), y + height], fill=fill)
        for i, lines in enumerate(cells):
            x2 = x + widths[i]
            draw.rectangle([x, y, x2, y + height], outline="#4F5B66", width=2 if row_index == 0 else 1)
            text_y = y + padding
            for line in lines:
                draw.text((x + padding, text_y), line, fill="black", font=current_font)
                text_y += line_height
            x = x2
        y += height
    img.save(output_path, "PNG")


def set_run_font(run, size=11, bold=None, italic=None, color=None):
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:ascii"), "Times New Roman")
    run._element.rPr.rFonts.set(qn("w:hAnsi"), "Times New Roman")
    run.font.size = Pt(size)
    if bold is not None:
        run.bold = bold
    if italic is not None:
        run.italic = italic
    if color is not None:
        run.font.color.rgb = RGBColor(*color)


def clear_body(doc):
    body = doc._body._element
    for child in list(body):
        if child.tag != qn("w:sectPr"):
            body.remove(child)


def clear_headers_and_footers(doc):
    for section in doc.sections:
        for part in [
            section.header,
            section.footer,
            section.first_page_header,
            section.first_page_footer,
            section.even_page_header,
            section.even_page_footer,
        ]:
            part.is_linked_to_previous = False
            for child in list(part._element):
                part._element.remove(child)


def add_para(doc, text="", size=11, before=0, after=6, align=None, bold=False, italic=False):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.space_after = Pt(after)
    p.paragraph_format.line_spacing = 1.0
    if align is not None:
        p.alignment = align
    if text:
        r = p.add_run(text)
        set_run_font(r, size=size, bold=bold, italic=italic)
    return p


def add_heading(doc, text, level):
    p = doc.add_heading(text, level=level)
    p.paragraph_format.keep_with_next = True
    p.paragraph_format.space_before = Pt(12 if level > 1 else 0)
    p.paragraph_format.space_after = Pt(6)
    size = 16 if level == 1 else 14 if level == 2 else 12
    for run in p.runs:
        set_run_font(run, size=size, bold=True, italic=(level == 3), color=(0, 0, 0))
    return p


def add_bullets(doc, items):
    for item in items:
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Inches(0.25)
        p.paragraph_format.first_line_indent = Inches(-0.15)
        p.paragraph_format.space_after = Pt(3)
        p.paragraph_format.line_spacing = 1.0
        r = p.add_run(f"- {item}")
        set_run_font(r, size=11)


def add_image(doc, image_path, width=6.45):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_after = Pt(6)
    p.add_run().add_picture(str(image_path), width=Inches(width))


